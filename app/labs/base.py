"""Lab handler base class and per-instance ephemeral state.

ISOLATION MODEL (dev build)
---------------------------
Each challenge that needs a live target has a LabHandler. A *lab instance* is a
per-user runtime identified by an unguessable id (the `lab_instances.id`), which
doubles as the routing token in the lab URL. The intentionally vulnerable code
lives ONLY in these handlers, mounted under the separate ``/labs`` blueprint —
never in the platform API or auth layer (see docs/ARCHITECTURE.md).

Per-instance mutable state (a fake user table, stored comments, an uploaded
file, a virtual filesystem) is held in-process, keyed by instance id. In
production each instance would instead be an isolated container/microVM with its
own network namespace; this in-process store is the dev stand-in and is wiped on
teardown or expiry.

The flag for an instance is generated by the orchestrator, stored server-side in
``lab_instances.flag``, and only *revealed* by the vulnerable target when the
intended exploit succeeds. The handler never *validates* a submitted flag — that
is done by the secure core API, so exploiting the lab can never shortcut scoring.
"""
from __future__ import annotations

import threading
from typing import Any

# instance_id -> arbitrary handler state. Guarded by a lock because the dev
# server may serve lab requests on multiple threads.
_STATE: dict[str, dict[str, Any]] = {}
_LOCK = threading.RLock()


def get_state(instance_id: str) -> dict[str, Any]:
    with _LOCK:
        return _STATE.setdefault(instance_id, {})


def clear_state(instance_id: str) -> None:
    with _LOCK:
        _STATE.pop(instance_id, None)


class LabResult:
    """Return type for a lab dispatch: body + status + headers/content-type."""

    def __init__(self, body: str, status: int = 200,
                 content_type: str = "text/html; charset=utf-8",
                 headers: dict | None = None):
        self.body = body
        self.status = status
        self.content_type = content_type
        self.headers = headers or {}


class LabHandler:
    kind = "base"
    # True for terminal labs (ShellLab): the UI renders a terminal, not an iframe.
    is_shell = False
    # Human description shown in the challenge panel.
    title = "Lab"

    # ---- lifecycle -------------------------------------------------------
    def provision(self, instance) -> None:
        """Initialise per-instance state. Called once at start/reset.

        `instance` is the sqlite row (has .id, .flag, .challenge_id, .user_id).
        """
        get_state(instance["id"])  # ensure a bucket exists

    def teardown(self, instance_id: str) -> None:
        clear_state(instance_id)

    # ---- request handling ------------------------------------------------
    def dispatch(self, instance, subpath: str, request) -> LabResult:
        raise NotImplementedError

    # ---- helpers ---------------------------------------------------------
    def base_url(self, instance) -> str:
        return f"/labs/{instance['id']}"

    def page(self, instance, title: str, body: str, *, head: str = "") -> str:
        """Wrap lab HTML in a minimal, self-contained, dark-themed shell.

        The lab UI is deliberately plain so learners focus on the target app.
        """
